// The parity matrix: every Ouro HX component and every core claim, across web, Apple, Android and Windows, with each gap
// shown as a cell rather than kept in a backlog. docs/platforms/parity.md is rendered from three sources, none typed by hand:
//
// - web's components, from each folder's component.json (scripts/components.mts reads the same manifests);
// - the other platforms' components, recorded in scripts/parity-data/platforms.json: Apple's from the SwiftUI views in
//   ouro-ui-apple's Sources/OuroHX/Components at the release versions.json names (WebNames.swift gives web's name where
//   Apple's differs), and Android's and Windows's from their kits' repositories, which do not exist yet;
// - core's component and action claims (scripts/parity-data/*.claims.json, the copies the Apple page's tables use).
//
//   node scripts/parity-matrix.mjs           fail when the page differs from what the data renders (offline)
//   node scripts/parity-matrix.mjs --render  rewrite the page from the data as it is, with no network (the Pages build runs it after core's copies are written)
//   node scripts/parity-matrix.mjs --live    also fail when platforms.json differs from GitHub (network)
//   node scripts/parity-matrix.mjs --write   read GitHub, then rewrite platforms.json and the page (network)
//
//   Exits 1 on drift (and writes behind=true to GITHUB_OUTPUT), 2 when GitHub cannot be read, which is no drift.
import { appendFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { sideState } from "./parity-rows.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PAGE = "docs/platforms/parity.md";
export const PLATFORMS = "scripts/parity-data/platforms.json";
const VERSIONS = "scripts/parity-data/versions.json";
const COMPONENTS_DIR = "registry/ouro/components/ouro";
const APPLE = "ourostack/ouro-ui-apple";
const KITS = { android: "ourostack/ouro-ui-android", windows: "ourostack/ouro-ui-windows" };
const START = "<!-- parity-matrix:start (generated by node scripts/parity-matrix.mjs --write; do not edit) -->";
const END = "<!-- parity-matrix:end -->";
const FIX = "Run node scripts/parity-matrix.mjs --write and commit what it changes.";

/** `EmptyState` to `empty-state`. */
export const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/**
 * Web's components, in registry order: the stems each folder's component.json lists. `folders` maps a folder to its first
 * stem, so another platform's component named after the folder (Apple's OuroToast, web's toast folder) meets its web twin
 * (toaster).
 */
export function webComponents(dir = join(root, COMPONENTS_DIR)) {
  const manifests = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, "component.json")))
    .map((entry) => ({ folder: entry.name, ...JSON.parse(readFileSync(join(dir, entry.name, "component.json"), "utf8")) }))
    .sort((a, b) => a.order - b.order || (a.folder < b.folder ? -1 : 1));
  return { names: manifests.flatMap((manifest) => manifest.components), folders: Object.fromEntries(manifests.map((manifest) => [manifest.folder, manifest.components[0]])) };
}

/**
 * Apple's components from the files of Sources/OuroHX/Components: each Ouro<Name>.swift that declares the component itself,
 * a public struct Ouro<Name> (a view such as OuroButton, or a value a modifier shows, such as OuroToast) or a public
 * ouro<Name>( modifier (OuroSheet), under web's name. Files of support types (OuroTone's enum) are not components.
 * WebNames.swift's renamed aliases (`typealias OuroEmpty… = OuroEmptyState…`) say where the names differ.
 */
export function appleComponents(files) {
  const webName = new Map();
  for (const text of Object.values(files)) {
    for (const match of text.matchAll(/typealias Ouro(\w+)(?:<[^>]*>)?\s*=\s*Ouro(\w+)/g)) webName.set(match[2], kebab(match[1]));
  }
  const views = new Set();
  for (const [path, text] of Object.entries(files)) {
    const name = /(?:^|\/)Ouro(\w+)\.swift$/.exec(path)?.[1];
    if (!name) continue;
    if (new RegExp(`public struct Ouro${name}\\b`).test(text) || new RegExp(`public func ouro${name}\\b`).test(text)) views.add(name);
  }
  return [...views].sort().map((name) => ({ name: `Ouro${name}`, web: webName.get(name) ?? kebab(name) }));
}

/** The four platforms' rows: one per web component, then any component only another platform has. */
export function componentMatrix({ names: web, folders = {} }, platforms) {
  const others = ["apple", "android", "windows"];
  const twin = (name) => (web.includes(name) ? name : (folders[name] ?? name));
  const byWeb = Object.fromEntries(others.map((id) => [id, new Map((platforms[id]?.components ?? []).map((component) => [twin(component.web), component.name]))]));
  const names = [...web, ...others.flatMap((id) => [...byWeb[id].keys()]).filter((name) => !web.includes(name))];
  return [...new Set(names)].map((name) => ({
    name,
    web: web.includes(name) ? name : null,
    apple: byWeb.apple.get(name) ?? null,
    android: byWeb.android.get(name) ?? null,
    windows: byWeb.windows.get(name) ?? null,
  }));
}

/** Where each action surface runs (parity-rows.mjs SURFACES), as the platform columns. */
const SURFACE_PLATFORM = { cli: "any", mcp: "any", webmcp: "web", "web-control": "web", "app-intent": "apple", "swiftui-button": "apple", reins: "apple" };

/** One row per core claim: a component claim's check on each platform, or the surfaces an action claim covers there. */
export function claimMatrix(componentClaims, actionClaims) {
  const component = componentClaims.claims.map((claim) => ({
    id: claim.id,
    tier: claim.tier,
    kind: "component",
    web: sideState(claim.checks?.web).state,
    apple: sideState(claim.checks?.apple).state,
    android: sideState(claim.checks?.android).state,
    windows: sideState(claim.checks?.windows).state,
  }));
  const action = actionClaims.claims.map((claim) => {
    const on = (platform) => claim.appliesTo.some((surface) => SURFACE_PLATFORM[surface] === platform || SURFACE_PLATFORM[surface] === "any");
    const state = (platform) => (on(platform) ? "checked" : "none");
    return { id: claim.id, tier: claim.tier, kind: "action", web: state("web"), apple: state("apple"), android: "none", windows: "none" };
  });
  return [...component, ...action];
}

const PLATFORM_NAMES = { web: "Web", apple: "Apple", android: "Android", windows: "Windows" };
const CLAIM_CELL = { checked: "Covered", partly: "Partly", none: "Not yet" };

/** The generated part of docs/platforms/parity.md. */
export function renderMatrix({ web, platforms, componentClaims, actionClaims }) {
  const components = componentMatrix(web, platforms);
  const claims = claimMatrix(componentClaims, actionClaims);
  const ids = ["web", "apple", "android", "windows"];
  const have = (id) => components.filter((row) => row[id]).length;
  const covered = (id) => claims.filter((row) => row[id] === "checked").length;
  const gaps = components.reduce((sum, row) => sum + ids.filter((id) => !row[id]).length, 0) + claims.reduce((sum, row) => sum + ids.filter((id) => row[id] !== "checked").length, 0);
  const kit = (id) => {
    if (id === "web") return "this repository";
    const platform = platforms[id];
    if (!platform?.repo) return "Not yet";
    return platform.tag ? `[${platform.repo} ${platform.tag}](https://github.com/${platform.repo}/releases/tag/${platform.tag} "verify:equals(${PLATFORMS}#${id}.tag)=${platform.tag}")` : `Not yet: [${platform.repo}](https://github.com/${platform.repo}) is waiting for a builder`;
  };
  const lines = [
    START,
    "",
    `| | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|${ids.map(() => "---").join("|")}|`,
    `| Kit | ${ids.map(kit).join(" | ")} |`,
    "",
    `Components: ${ids.map((id) => `${PLATFORM_NAMES[id]} has ${have(id)} of ${components.length}`).join(", ")}.[^matrix]`,
    "",
    `Claims covered: ${ids.map((id) => `${PLATFORM_NAMES[id]} ${covered(id)} of ${claims.length}`).join(", ")}.[^matrix]`,
    "",
    `Gap cells: ${gaps}.[^matrix]`,
    "",
    "### Components",
    "",
    `| Component | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|${ids.map(() => "---").join("|")}|`,
    ...components.map((row) => `| ${row.web ? `[${row.name}](https://ui.ouroboros.bot/docs/${row.name}/)` : row.name} | ${ids.map((id) => (row[id] ? `\`${id === "web" ? row.name : row[id]}\`` : "Not yet")).join(" | ")} |`),
    "",
    "### Claims",
    "",
    `| Claim | Tier | Kind | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|---|---|${ids.map(() => "---").join("|")}|`,
    ...claims.map((row) => `| \`${row.id}\` | ${row.tier} | ${row.kind} | ${ids.map((id) => CLAIM_CELL[row[id]]).join(" | ")} |`),
    "",
    END,
  ];
  return lines.join("\n");
}

/** The page with its generated part replaced. */
export function renderPage(page, data) {
  const start = page.indexOf(START);
  const end = page.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${PAGE} has lost its generated region's markers. ${FIX}`);
  return `${page.slice(0, start)}${renderMatrix(data)}${page.slice(end + END.length)}`;
}

/** The data the page renders from, read from the repository. */
export function readData(read = (path) => readFileSync(join(root, path), "utf8")) {
  return {
    web: webComponents(),
    platforms: JSON.parse(read(PLATFORMS)),
    componentClaims: JSON.parse(read("scripts/parity-data/components.claims.json")),
    actionClaims: JSON.parse(read("scripts/parity-data/actions.claims.json")),
  };
}

export class Unreadable extends Error {}

/** platforms.json's facts, read from GitHub: Apple's components at the release versions.json names, and whether each other kit exists. */
export async function gather({ fetch = globalThis.fetch, token, apple }) {
  const get = async (url, { allow404 = false } = {}) => {
    const response = await fetch(url, { headers: token ? { authorization: `Bearer ${token}` } : {} });
    if (allow404 && response.status === 404) return null;
    if (!response.ok) throw new Unreadable(`${url} answered ${response.status}`);
    return response;
  };
  const tree = await (await get(`https://api.github.com/repos/${APPLE}/git/trees/${apple.commit}?recursive=1`)).json();
  const paths = tree.tree.map((node) => node.path).filter((path) => /^Sources\/OuroHX\/Components\/[^/]+\.swift$/.test(path));
  const files = {};
  for (const path of paths) files[path] = await (await get(`https://raw.githubusercontent.com/${APPLE}/${apple.commit}/${path}`)).text();
  const facts = { $comment: `Generated by node scripts/parity-matrix.mjs --write from GitHub; do not edit. ${PAGE} is rendered from it.`, apple: { repo: APPLE, tag: apple.tag, commit: apple.commit, components: appleComponents(files) } };
  for (const [id, repo] of Object.entries(KITS)) {
    const found = await get(`https://api.github.com/repos/${repo}`, { allow404: true });
    const latest = found && (await get(`https://api.github.com/repos/${repo}/releases/latest`, { allow404: true }));
    facts[id] = { repo, tag: latest ? (await latest.json()).tag_name : null, components: [] };
  }
  return facts;
}

async function main(args) {
  const read = (path) => readFileSync(join(root, path), "utf8");
  const report = (problems) => {
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `behind=${problems.length > 0}\n`);
    for (const problem of problems) console.log(`::error::${problem}`);
    return problems.length > 0 ? 1 : 0;
  };
  if (args.includes("--render")) {
    writeFileSync(join(root, PAGE), renderPage(read(PAGE), readData(read)));
    console.log(`Rendered ${PAGE} from its data.`);
    return 0;
  }
  if (args.includes("--live") || args.includes("--write")) {
    let facts;
    try {
      facts = await gather({ token: process.env.GH_TOKEN, apple: JSON.parse(read(VERSIONS)).apple });
    } catch (error) {
      if (!(error instanceof Unreadable)) throw error;
      console.log(`::error::${error.message}. Not drift: run it again later.`);
      return 2;
    }
    const text = `${JSON.stringify(facts, null, 2)}\n`;
    if (args.includes("--write")) {
      writeFileSync(join(root, PLATFORMS), text);
      writeFileSync(join(root, PAGE), renderPage(read(PAGE), readData(read)));
      console.log(`Wrote ${PLATFORMS} and ${PAGE}.`);
      return 0;
    }
    if (text !== read(PLATFORMS)) return report([`${PLATFORMS} differs from GitHub (a kit's components changed, or a kit now exists). ${FIX}`]);
  }
  const problems = renderPage(read(PAGE), readData(read)) === read(PAGE) ? [] : [`${PAGE} differs from what its data renders. ${FIX}`];
  if (problems.length === 0) console.log(`${PAGE} shows what its data says.`);
  return report(problems);
}

if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
