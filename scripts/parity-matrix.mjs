// The parity matrix: every Ouro HX component and every core claim, across web, Apple, Android and Windows, with each gap
// shown as a cell rather than kept in a backlog. docs/platforms/parity.md is rendered from three sources, none typed by hand:
//
// - web's components, from each folder's component.json (scripts/components.mts reads the same manifests);
// - the other platforms' components, recorded in scripts/parity-data/platforms.json: Apple's from the SwiftUI views in
//   ouro-ui-apple's Sources/OuroHX/Components at the release versions.json names (WebNames.swift gives web's name where
//   Apple's differs), and Windows's from the WinUI controls in ouro-ui-windows' src/Ouro.UI.Windows at its newest release
//   (Ouro<Name>.cs, under web's name in kebab case), with the claims its vendored component specs name, which its CI
//   checks on Windows (tools/claims.mts), and Android's from the Compose functions in ouro-ui-android's ouro-hx at its
//   newest release (Ouro<Name>.kt, under web's name in kebab case), with the claims its vendored component specs name;
// - core's component and action claims (scripts/parity-data/*.claims.json, the copies the Apple page's tables use).
//
//   node scripts/parity-matrix.mjs           fail when the page differs from what the data renders (offline)
//   node scripts/parity-matrix.mjs --render  rewrite the page from the data as it is, with no network (the Pages build runs it last)
//   node scripts/parity-matrix.mjs --live    also fail when platforms.json's Apple components differ from the release versions.json pins (network)
//   node scripts/parity-matrix.mjs --live --pins  only that: on main, Core pin re-renders a page a race left behind (core-pin.yml)
//   node scripts/parity-matrix.mjs --write   read GitHub, then rewrite platforms.json and the page (network; the Pages build runs it)
//   node scripts/parity-matrix.mjs --write --kit <apple|android|windows>  read only that kit, keeping the others as platforms.json has
//                                            them (Kit pin runs it for the kit it pins, kit-pin.yml)
//
//   --live holds only what is pinned. The kits' newest releases are not checked: --write reads them when the Pages build
//   runs, so no kit's release can fail --live.
//
//   Exits 1 on drift (and writes behind=true to GITHUB_OUTPUT), 2 when GitHub cannot be read, which is no drift.
import { appendFileSync, existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { setTimeout as delay } from "node:timers/promises";
import { fileURLToPath } from "node:url";
import { sideState } from "./parity-rows.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
export const PAGE = "docs/platforms/parity.md";
export const PLATFORMS = "scripts/parity-data/platforms.json";
const VERSIONS = "scripts/parity-data/versions.json";
const COMPONENTS_DIR = "registry/ouro/components/ouro";
const APPLE = "ourostack/ouro-ui-apple";
const APPLE_FILES = /^Sources\/OuroHX\/Components\/[^/]+\.swift$/;
const KITS = { android: "ourostack/ouro-ui-android", windows: "ourostack/ouro-ui-windows" };
/** Where a kit's component sources are, and how they become components. */
const KIT_SOURCES = {
  android: { files: /^ouro-hx\/src\/main\/kotlin\/.+\/Ouro\w+\.kt$/, components: androidComponents, specs: /^vendor\/core\/components\/[^/]+\.spec\.json$/ },
  windows: { files: /^src\/Ouro\.UI\.Windows\/[^/]+\.cs$/, components: windowsComponents, specs: /^vendor\/core\/components\/[^/]+\.spec\.json$/ },
};
const START = "<!-- parity-matrix:start (generated by node scripts/parity-matrix.mjs --write; do not edit) -->";
const END = "<!-- parity-matrix:end -->";
const FIX = "Run node scripts/parity-matrix.mjs --write and commit what it changes.";

/** `EmptyState` to `empty-state`. */
export const kebab = (name) => name.replace(/([a-z0-9])([A-Z])/g, "$1-$2").toLowerCase();

/**
 * Web's components, in registry order: the stems each folder's component.json lists. `folders` maps a folder to its first
 * stem, so another platform's component named after the folder (Apple's OuroToast, web's toast folder) meets its web twin
 * (toaster).
 */
export function webComponents(dir = join(root, COMPONENTS_DIR)) {
  const manifests = readdirSync(dir, { withFileTypes: true })
    .filter((entry) => entry.isDirectory() && existsSync(join(dir, entry.name, "component.json")))
    .map((entry) => ({ folder: entry.name, ...JSON.parse(readFileSync(join(dir, entry.name, "component.json"), "utf8")) }))
    .sort((a, b) => a.order - b.order || (a.folder < b.folder ? -1 : 1));
  return { names: manifests.flatMap((manifest) => manifest.components), folders: Object.fromEntries(manifests.map((manifest) => [manifest.folder, manifest.components[0]])) };
}

/**
 * Apple's components from the files of Sources/OuroHX/Components: each Ouro<Name>.swift that declares the component itself,
 * a public struct Ouro<Name> (a view such as OuroButton, or a value a modifier shows, such as OuroToast) or a public
 * ouro<Name>( modifier (OuroSheet), and every other public struct Ouro<Other> that is a View, since one file can hold a
 * family (OuroLoading.swift: OuroSkeleton, OuroSpinner and OuroProgress), under web's name. Support types (OuroTone's
 * enum, a palette, OuroSegment) are not components.
 * WebNames.swift's renamed aliases (`typealias OuroEmpty… = OuroEmptyState…`) say where the names differ. A view that is a
 * part of another component (APPLE_PARTS) is not one either.
 */
export function appleComponents(files) {
  const webName = new Map();
  for (const text of Object.values(files)) {
    for (const match of text.matchAll(/typealias Ouro(\w+)(?:<[^>]*>)?\s*=\s*Ouro(\w+)/g)) webName.set(match[2], kebab(match[1]));
  }
  const views = new Set();
  for (const [path, text] of Object.entries(files)) {
    const name = /(?:^|\/)Ouro(\w+)\.swift$/.exec(path)?.[1];
    if (!name) continue;
    if (new RegExp(`public struct Ouro${name}\\b`).test(text) || new RegExp(`public func ouro${name}\\b`).test(text)) views.add(name);
    for (const match of text.matchAll(/public struct Ouro(\w+)(?:<[^{]*?>)?\s*:[^{]*\bView\b/g)) views.add(match[1]);
  }
  return [...views].filter((name) => !APPLE_PARTS.has(name)).sort().map((name) => ({ name: `Ouro${name}`, web: webName.get(name) ?? kebab(name) }));
}

/**
 * Apple views that are parts of a component, not components: ouro-ui-apple's Components.md lists each inside its
 * component's row, and web draws the same thing inside that component. A name alone can't tell a part from a component
 * declared beside another (OuroItemGroup lives in OuroItem.swift and is web's item-group), so the parts are named here.
 * OuroCheckboxMark (v1.4.0) is Checkbox's box on its own, for an app's own rows.
 */
const APPLE_PARTS = new Set(["CheckboxMark"]);

/**
 * Windows's components from the files of src/Ouro.UI.Windows: each Ouro<Name>.cs whose public class Ouro<Name> derives from a
 * XAML control (`: Button`, `: Control`), under web's name in kebab case. The static helpers (OuroPaint, OuroPerson, OuroUI)
 * declare no base class, and the automation peers share a file with their control but are named differently, so none of them
 * is a component.
 */
export function windowsComponents(files) {
  return Object.entries(files)
    .flatMap(([path, text]) => {
      const name = /(?:^|\/)Ouro(\w+)\.cs$/.exec(path)?.[1];
      if (!name || !new RegExp(`public\\s+(?:(?:sealed|partial)\\s+)*class\\s+Ouro${name}\\s*:`).test(text)) return [];
      return [{ name: `Ouro${name}`, web: kebab(name) }];
    })
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

/**
 * Android's components from the Kotlin files of ouro-hx: each Ouro<Name>.kt that declares a composable `fun Ouro<Name>(`,
 * under web's name in kebab case. OuroTheme wraps the others and is not a component, and the helper files (OuroColor,
 * OuroPaint, OuroSemantics) declare no composable of their own name.
 */
export function androidComponents(files) {
  return Object.entries(files)
    .flatMap(([path, text]) => {
      const name = /(?:^|\/)Ouro(\w+)\.kt$/.exec(path)?.[1];
      if (!name || name === "Theme" || !new RegExp(`@Composable\\s+fun\\s+(?:<[^>]*>\\s+)?Ouro${name}\\(`).test(text)) return [];
      return [{ name: `Ouro${name}`, web: kebab(name) }];
    })
    .sort((a, b) => (a.name < b.name ? -1 : 1));
}

/** The claims a kit's vendored component specs name, which its CI must check on its platform to pass. */
export function kitClaims(specs) {
  return [...new Set(Object.values(specs).flatMap((text) => JSON.parse(text).claims ?? []))].sort();
}

/** The four platforms' rows: one per web component, then any component only another platform has. */
export function componentMatrix({ names: web, folders = {} }, platforms) {
  const others = ["apple", "android", "windows"];
  const twin = (name) => (web.includes(name) ? name : (folders[name] ?? name));
  const byWeb = Object.fromEntries(others.map((id) => [id, new Map((platforms[id]?.components ?? []).map((component) => [twin(component.web), component.name]))]));
  const names = [...web, ...others.flatMap((id) => [...byWeb[id].keys()]).filter((name) => !web.includes(name))];
  return [...new Set(names)].map((name) => ({
    name,
    web: web.includes(name) ? name : null,
    apple: byWeb.apple.get(name) ?? null,
    android: byWeb.android.get(name) ?? null,
    windows: byWeb.windows.get(name) ?? null,
  }));
}

/** Where each action surface runs (parity-rows.mjs SURFACES), as the platform columns. */
const SURFACE_PLATFORM = { cli: "any", mcp: "any", webmcp: "web", "web-control": "web", "app-intent": "apple", "swiftui-button": "apple", reins: "apple" };

/** One row per core claim: a component claim's check on each platform, or the surfaces an action claim covers there. */
export function claimMatrix(componentClaims, actionClaims, platforms = {}) {
  const windowsChecks = new Set(platforms.windows?.claims ?? []);
  const androidChecks = new Set(platforms.android?.claims ?? []);
  const component = componentClaims.claims.map((claim) => ({
    id: claim.id,
    tier: claim.tier,
    kind: "component",
    web: sideState(claim.checks?.web).state,
    apple: sideState(claim.checks?.apple).state,
    android: androidChecks.has(claim.id) ? "checked" : sideState(claim.checks?.android).state,
    windows: windowsChecks.has(claim.id) ? "checked" : sideState(claim.checks?.windows).state,
  }));
  const action = actionClaims.claims.map((claim) => {
    const on = (platform) => claim.appliesTo.some((surface) => SURFACE_PLATFORM[surface] === platform || SURFACE_PLATFORM[surface] === "any");
    const state = (platform) => (on(platform) ? "checked" : "none");
    return { id: claim.id, tier: claim.tier, kind: "action", web: state("web"), apple: state("apple"), android: "none", windows: "none" };
  });
  return [...component, ...action];
}

const PLATFORM_NAMES = { web: "Web", apple: "Apple", android: "Android", windows: "Windows" };
const CLAIM_CELL = { checked: "Covered", partly: "Partly", none: "Not yet" };

/** The generated part of docs/platforms/parity.md. */
export function renderMatrix({ web, platforms, componentClaims, actionClaims }) {
  const components = componentMatrix(web, platforms);
  const claims = claimMatrix(componentClaims, actionClaims, platforms);
  const ids = ["web", "apple", "android", "windows"];
  const have = (id) => components.filter((row) => row[id]).length;
  const covered = (id) => claims.filter((row) => row[id] === "checked").length;
  const gaps = components.reduce((sum, row) => sum + ids.filter((id) => !row[id]).length, 0) + claims.reduce((sum, row) => sum + ids.filter((id) => row[id] !== "checked").length, 0);
  const kit = (id) => {
    if (id === "web") return "this repository";
    const platform = platforms[id];
    if (!platform?.repo) return "Not yet";
    return platform.tag ? `[${platform.repo} ${platform.tag}](https://github.com/${platform.repo}/releases/tag/${platform.tag} "verify:equals(${PLATFORMS}#${id}.tag)=${platform.tag}")` : `Not yet: [${platform.repo}](https://github.com/${platform.repo}) is waiting for a builder`;
  };
  const lines = [
    START,
    "",
    `| | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|${ids.map(() => "---").join("|")}|`,
    `| Kit | ${ids.map(kit).join(" | ")} |`,
    "",
    `Components: ${ids.map((id) => `${PLATFORM_NAMES[id]} has ${have(id)} of ${components.length}`).join(", ")}.[^matrix]`,
    "",
    `Claims covered: ${ids.map((id) => `${PLATFORM_NAMES[id]} ${covered(id)} of ${claims.length}`).join(", ")}.[^matrix]`,
    "",
    `Gap cells: ${gaps}.[^matrix]`,
    "",
    "### Components",
    "",
    `| Component | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|${ids.map(() => "---").join("|")}|`,
    ...components.map((row) => `| ${row.web ? `[${row.name}](https://ui.ouroboros.bot/docs/${row.name}/)` : row.name} | ${ids.map((id) => (row[id] ? `\`${id === "web" ? row.name : row[id]}\`` : "Not yet")).join(" | ")} |`),
    "",
    "### Claims",
    "",
    `| Claim | Tier | Kind | ${ids.map((id) => PLATFORM_NAMES[id]).join(" | ")} |`,
    `|---|---|---|${ids.map(() => "---").join("|")}|`,
    ...claims.map((row) => `| \`${row.id}\` | ${row.tier} | ${row.kind} | ${ids.map((id) => CLAIM_CELL[row[id]]).join(" | ")} |`),
    "",
    END,
  ];
  return lines.join("\n");
}

/** The page with its generated part replaced. */
export function renderPage(page, data) {
  const start = page.indexOf(START);
  const end = page.indexOf(END);
  if (start < 0 || end < start) throw new Error(`${PAGE} has lost its generated region's markers. ${FIX}`);
  return `${page.slice(0, start)}${renderMatrix(data)}${page.slice(end + END.length)}`;
}

/** The data the page renders from, read from the repository. */
export function readData(read = (path) => readFileSync(join(root, path), "utf8")) {
  return {
    web: webComponents(),
    platforms: JSON.parse(read(PLATFORMS)),
    componentClaims: JSON.parse(read("scripts/parity-data/components.claims.json")),
    actionClaims: JSON.parse(read("scripts/parity-data/actions.claims.json")),
  };
}

export class Unreadable extends Error {}

/**
 * How long to wait before each retry of a 5xx or a network error: 5s, then 20s. Three attempts total, so a GitHub 503
 * (ourostack/ouro-ui-apple's run 45308495839) that clears before the third try never reaches Unreadable. A 4xx (a 404 is
 * real drift) throws on the first try, with no retry.
 */
const RETRY_DELAYS_MS = [5000, 20000];

/**
 * A GET that returns null for a 404 when `allow404`, retries a 5xx or a network error up to twice (the delays above,
 * logged before each), and throws Unreadable for a 4xx straight away or once the retries are spent.
 */
const client = (fetch, token, { wait = (ms) => delay(ms), log = console.log } = {}) =>
  async (url, { allow404 = false } = {}) => {
    for (let attempt = 0; ; attempt++) {
      let response;
      let networkError;
      try {
        response = await fetch(url, { headers: token ? { authorization: `Bearer ${token}` } : {} });
      } catch (error) {
        networkError = error;
      }
      if (!networkError) {
        if (allow404 && response.status === 404) return null;
        if (response.ok) return response;
        if (response.status < 500) throw new Unreadable(`${url} answered ${response.status}`);
      }
      const message = networkError ? `${url}: ${networkError.message}` : `${url} answered ${response.status}`;
      if (attempt >= RETRY_DELAYS_MS.length) throw new Unreadable(message);
      const delayMs = RETRY_DELAYS_MS[attempt];
      log(`::warning::${message}. Retrying in ${delayMs / 1000}s (attempt ${attempt + 2} of ${RETRY_DELAYS_MS.length + 1}).`);
      await wait(delayMs);
    }
  };

/** The text of every file under a commit whose path matches `pattern`, by path. */
async function readFiles(get, repo, commit, pattern) {
  const tree = await (await get(`https://api.github.com/repos/${repo}/git/trees/${commit}?recursive=1`)).json();
  const files = {};
  for (const path of tree.tree.map((node) => node.path).filter((path) => pattern.test(path))) {
    files[path] = await (await get(`https://raw.githubusercontent.com/${repo}/${commit}/${path}`)).text();
  }
  return files;
}

/** Apple's facts: its components at the release versions.json pins, which the scheduled check holds to GitHub. */
export async function gatherApple({ fetch = globalThis.fetch, token, apple, wait, log }) {
  const files = await readFiles(client(fetch, token, { wait, log }), APPLE, apple.commit, APPLE_FILES);
  return { repo: APPLE, tag: apple.tag, commit: apple.commit, components: appleComponents(files) };
}

/**
 * Each other kit's newest release, its commit and the components its source names, with a note for a kit whose repository
 * does not exist. Given `only`, it reads that kit alone and keeps each other kit as `stored` has it.
 */
export async function gatherKits({ fetch = globalThis.fetch, token, only, stored, wait, log }) {
  const get = client(fetch, token, { wait, log });
  const kits = {};
  for (const [id, repo] of Object.entries(KITS)) {
    if (only !== undefined && id !== only) {
      kits[id] = stored[id];
      continue;
    }
    const found = await get(`https://api.github.com/repos/${repo}`, { allow404: true });
    const latest = found && (await get(`https://api.github.com/repos/${repo}/releases/latest`, { allow404: true }));
    const tag = latest ? (await latest.json()).tag_name : null;
    const commit = tag ? (await (await get(`https://api.github.com/repos/${repo}/commits/${tag}`)).json()).sha : null;
    const source = KIT_SOURCES[id];
    const components = source && commit ? source.components(await readFiles(get, repo, commit, source.files)) : [];
    kits[id] = { repo, tag, commit, components };
    if (source?.specs && commit) kits[id].claims = kitClaims(await readFiles(get, repo, commit, source.specs));
  }
  return kits;
}

/** platforms.json's facts, read from GitHub: every kit's, or with `only`, that kit's, and the others as `stored` has them. */
export async function gather(options) {
  return {
    $comment: `Generated by node scripts/parity-matrix.mjs --write from GitHub; do not edit. ${PAGE} is rendered from it.`,
    apple: options.only === undefined || options.only === "apple" ? await gatherApple(options) : options.stored.apple,
    ...(await gatherKits(options)),
  };
}


/**
 * What `--live` reports: platforms.json's Apple components against the components of the release versions.json pins, read
 * from GitHub. A kit's newer release is no drift; the Pages build writes it.
 */
export function pinnedDrift(stored, apple) {
  if (JSON.stringify(apple) === JSON.stringify(stored.apple)) return [];
  return [`${PLATFORMS}'s Apple components differ from ${apple.tag} on GitHub, the release ${VERSIONS} pins. ${FIX}`];
}

async function main(args) {
  const read = (path) => readFileSync(join(root, path), "utf8");
  const report = (problems) => {
    if (process.env.GITHUB_OUTPUT) appendFileSync(process.env.GITHUB_OUTPUT, `behind=${problems.length > 0}\n`);
    for (const problem of problems) console.log(`::error::${problem}`);
    return problems.length > 0 ? 1 : 0;
  };
  const unreadable = (error) => {
    if (!(error instanceof Unreadable)) throw error;
    console.log(`::error::${error.message}. Not drift: run it again later.`);
    return 2;
  };
  if (args.includes("--render")) {
    writeFileSync(join(root, PAGE), renderPage(read(PAGE), readData(read)));
    console.log(`Rendered ${PAGE} from its data.`);
    return 0;
  }
  if (args.includes("--write")) {
    const only = args.includes("--kit") ? args[args.indexOf("--kit") + 1] : undefined;
    if (only !== undefined && only !== "apple" && !(only in KITS)) {
      console.log(`::error::--kit takes apple, ${Object.keys(KITS).join(" or ")}, not ${only}.`);
      return 1;
    }
    const stored = only === undefined ? undefined : JSON.parse(read(PLATFORMS));
    let facts;
    try {
      facts = await gather({ token: process.env.GH_TOKEN, apple: JSON.parse(read(VERSIONS)).apple, only, stored });
    } catch (error) {
      return unreadable(error);
    }
    writeFileSync(join(root, PLATFORMS), `${JSON.stringify(facts, null, 2)}\n`);
    writeFileSync(join(root, PAGE), renderPage(read(PAGE), readData(read)));
    console.log(`Wrote ${PLATFORMS} and ${PAGE}.`);
    return 0;
  }
  if (args.includes("--live")) {
    let apple;
    try {
      apple = await gatherApple({ token: process.env.GH_TOKEN, apple: JSON.parse(read(VERSIONS)).apple });
    } catch (error) {
      return unreadable(error);
    }
    const problems = pinnedDrift(JSON.parse(read(PLATFORMS)), apple);
    if (problems.length > 0 || args.includes("--pins")) {
      if (problems.length === 0) console.log(`${PLATFORMS}'s Apple components are ${apple.tag}'s on GitHub.`);
      return report(problems);
    }
  }
  const problems = renderPage(read(PAGE), readData(read)) === read(PAGE) ? [] : [`${PAGE} differs from what its data renders. ${FIX}`];
  if (problems.length === 0) console.log(`${PAGE} shows what its data says.`);
  return report(problems);
}


if (process.argv[1] === fileURLToPath(import.meta.url)) process.exitCode = await main(process.argv.slice(2));
