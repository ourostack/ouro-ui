test("attribution passes the app's commit that only merges main into a branch, and fails one that adds content", () => {
  const dir = scratchDir("ouro-main-merge-");
  const bot = { GIT_AUTHOR_NAME: "ouro-current[bot]", GIT_AUTHOR_EMAIL: OURO_CURRENT, GIT_COMMITTER_NAME: "ouro-current[bot]", GIT_COMMITTER_EMAIL: OURO_CURRENT };
  const git = (args, env = {}) => execFileSync("git", args, { cwd: dir, encoding: "utf8", env: { ...process.env, ...env } }).trim();
  const write = (name, text) => writeFileSync(join(dir, name), text);
  git(["init", "-q", "-b", "main"]);
  git(["config", "user.name", MAINTAINER.name]);
  git(["config", "user.email", MAINTAINER.email]);
  write("a", "a\n");
  git(["add", "."]);
  git(["commit", "-qm", "Start"]);
  git(["checkout", "-qb", "feature"]);
  write("b", "b\n");
  git(["add", "."]);
  git(["commit", "-qm", "Feature"]);
  git(["checkout", "-q", "main"]);
  write("c", "c\n");
  git(["add", "."]);
  git(["commit", "-qm", "Main moves"]);
  const base = git(["rev-parse", "main"]);
  git(["checkout", "-q", "feature"]);
  git(["merge", "-q", "--no-ff", "-m", "Merge branch 'main' into feature", "main"], bot);
  const pure = git(["rev-parse", "HEAD"]);
  assert.equal(isMainMerge(pure, base, (args) => git(args)), true);
  assert.deepEqual(problems(readCommits(base, pure, (args) => git(args))), []);
  // The same merge with an extra file in it adds content main lacks.
  write("extra", "x\n");
  git(["add", "."]);
  git(["commit", "-q", "--amend", "--no-edit"], bot);
  const loaded = git(["rev-parse", "HEAD"]);
  assert.equal(isMainMerge(loaded, base, (args) => git(args)), false);
  assert.deepEqual(fieldsOf(readCommits(base, loaded, (args) => git(args))), ["author", "committer"]);
  // A plain commit by the app, or a merge whose second parent is not on the base, fails too.
  write("d", "d\n");
  git(["add", "."]);
  git(["commit", "-qm", "Plain"], bot);
  assert.equal(isMainMerge(git(["rev-parse", "HEAD"]), base, (args) => git(args)), false);
  assert.equal(isMainMerge(pure, git(["rev-parse", "feature~3"]), (args) => git(args)), false);
  assert.equal(isMainMerge(pure, base, () => { throw new Error("git failed"); }), false);
});
