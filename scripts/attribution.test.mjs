import assert from "node:assert/strict";
import { execFileSync, spawnSync } from "node:child_process";
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { test } from "node:test";
import { fileURLToPath } from "node:url";
import { AUTHORS, COMMITTERS, GITHUB, MAINTAINER, main, problems, readCommits, RELEASE_BOT, REAUTHOR, REWORD, UNCREDIT } from "./attribution.mjs";
import { scratchDir } from "./scratch.mjs";

const script = join(dirname(fileURLToPath(import.meta.url)), "attribution.mjs");
const maintainer = `${MAINTAINER.name} <${MAINTAINER.email}>`;

/** A commit as readCommits returns it: the maintainer's, committed by GitHub, unless overridden. */
const commit = (fields = {}) => ({ sha: "a".repeat(40), authorName: MAINTAINER.name, authorEmail: MAINTAINER.email, committerName: "GitHub", committerEmail: GITHUB, message: "Button: a fix (#1)", ...fields });
const fieldsOf = (commits) => problems(commits).map(({ field }) => field);

test("attribution passes the maintainer's commits, GitHub's squash commits and release.yml's", () => {
  assert.deepEqual(AUTHORS, [MAINTAINER.email, RELEASE_BOT]);
  assert.deepEqual(COMMITTERS, [MAINTAINER.email, RELEASE_BOT, GITHUB]);
  const passing = [
    commit(),
    commit({ committerName: MAINTAINER.name, committerEmail: MAINTAINER.email }),
    // Case never matters in an address.
    commit({ authorEmail: MAINTAINER.email.toUpperCase(), committerEmail: "NoReply@GitHub.com" }),
    // release.yml's "Prepare main for the next release", and the trailer GitHub puts on its squash.
    commit({ authorName: "github-actions[bot]", authorEmail: RELEASE_BOT, committerName: "github-actions[bot]", committerEmail: RELEASE_BOT, message: "Prepare main for the next release" }),
    commit({ message: `Prepare main for the next release (#248)\n\nCo-authored-by: github-actions[bot] <${RELEASE_BOT}>\nCo-authored-by: ${maintainer}` }),
    // This repository's own words for generated files, and agents, are no attribution.
    commit({ message: "Skeleton: regenerated docs\n\n* Ouro AX kit: the generated --why names who asked\n* docs generated by pnpm run docs for agents and AI readers\n\nSigned-off-by: " + maintainer }),
  ];
  assert.deepEqual(problems(passing), []);
});

test("attribution fails an author or committer other than the maintainer, GitHub or release.yml, with the re-author fix", () => {
  const copilot = { name: "copilot-swe-agent[bot]", email: "198982749+Copilot@users.noreply.github.com" };
  const found = problems([
    commit({ sha: "b".repeat(40), authorName: copilot.name, authorEmail: copilot.email }),
    commit({ sha: "c".repeat(40), committerName: "Someone", committerEmail: "someone@example.com" }),
    // GitHub may commit, never author.
    commit({ sha: "d".repeat(40), authorName: "GitHub", authorEmail: GITHUB }),
  ]);
  assert.deepEqual(
    found.map(({ sha, field }) => `${sha[0]} ${field}`),
    ["b author", "c committer", "d author"],
  );
  assert.match(found[0].problem, /copilot-swe-agent\[bot\] <198982749\+Copilot@users\.noreply\.github\.com> may not author here/);
  for (const { fix } of found) assert.equal(fix, REAUTHOR);
  // The fix is one line that re-authors every commit with the four variables set.
  assert.doesNotMatch(REAUTHOR, /\n/);
  for (const variable of ["GIT_AUTHOR_NAME", "GIT_AUTHOR_EMAIL", "GIT_COMMITTER_NAME", "GIT_COMMITTER_EMAIL"]) assert.match(REAUTHOR, new RegExp(`${variable}=`));
  assert.match(REAUTHOR, /git rebase origin\/main --exec 'git commit --amend --no-edit --reset-author'/);
});

test("attribution fails a trailer that credits an AI tool or any bot, in any case, as the squash message writes it too", () => {
  const credits = [
    "Co-authored-by: copilot-swe-agent[bot] <198982749+Copilot@users.noreply.github.com>",
    "Co-authored-by: Copilot <198982749+Copilot@users.noreply.github.com>",
    "co-authored-by: Claude <noreply@anthropic.com>",
    "CO-AUTHORED-BY: Claude Opus <noreply@example.com>",
    "Co-authored-by: Anthropic <ai@example.com>",
    "Co-authored-by: OpenAI Codex <codex@openai.com>",
    "Co-authored-by: ChatGPT <chatgpt@example.com>",
    "Co-authored-by: Gemini <gemini@example.com>",
    "Co-authored-by: Cursor Agent <cursoragent@cursor.com>",
    "Co-authored-by: Devin AI <158243242+devin-ai-integration[bot]@users.noreply.github.com>",
    "Co-authored-by: aider (gpt-4o) <noreply@aider.chat>",
    "Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>",
    "Assisted-by: GitHub Copilot",
    "Co-developed-by: Claude",
    // A one-line commit message, as the squash bullets it.
    "* Co-authored-by: Claude <noreply@anthropic.com>",
  ];
  for (const line of credits) {
    const found = problems([commit({ message: `Button: a fix (#1)\n\n${line}` })]);
    assert.deepEqual(
      found.map(({ field, fix }) => [field, fix]),
      [["message line 3", UNCREDIT]],
      line,
    );
    assert.match(found[0].problem, /credits an AI tool or a bot/);
  }
  // Only release.yml's own bot, exactly, may be credited.
  assert.deepEqual(fieldsOf([commit({ message: `x\n\nCo-authored-by: github-actions[bot] <1+someone@users.noreply.github.com>` })]), ["message line 3"]);
  // A person is no AI, and neither is a sentence that is no trailer.
  assert.deepEqual(fieldsOf([commit({ message: `x\n\nCo-authored-by: ${maintainer}\nThe agent wrote by hand: authored by the maintainer.` })]), []);
  // The fix drops the line and re-authors, since GitHub credits every other commit author in the squash.
  assert.match(UNCREDIT, /git rebase -i origin\/main/);
  assert.match(UNCREDIT, /--reset-author/);
  assert.doesNotMatch(UNCREDIT, /\n/);
});

test("attribution fails a line saying an AI tool generated the commit, and the robot emoji's footer", () => {
  const lines = [
    "🤖 Generated with [Claude Code](https://claude.com/claude-code)",
    "🤖 generated with something",
    "Generated with GitHub Copilot",
    "This change was generated by ChatGPT.",
    "GENERATED BY CODEX",
    "Generated with Cursor",
    "Generated by an AI",
    "generated by AI",
    "Generated with Gemini 2.5",
  ];
  for (const line of lines) {
    const found = problems([commit({ message: `Docs: a fix (#2)\n\n${line}` })]);
    assert.deepEqual(
      found.map(({ field, fix }) => [field, fix]),
      [["message line 3", REWORD]],
      line,
    );
    assert.match(found[0].problem, /says an AI tool wrote it/);
  }
  assert.doesNotMatch(REWORD, /\n/);
  // Generated by a tool that is no AI, or AI named later in the sentence, is no attribution.
  assert.deepEqual(fieldsOf([commit({ message: "x\n\nGenerated by pnpm registry\nThe docs are generated by gen-docs, which AI agents read." })]), []);
});

/** A repository in a scratch folder with these commits on main, each `{ message, author?, committer? }`; returns its folder and their SHAs. */
function repository(commits) {
  const dir = scratchDir("ouro-attribution-");
  const git = (args, env = {}) => execFileSync("git", args, { cwd: dir, encoding: "utf8", env: { ...process.env, ...env } }).trim();
  git(["init", "--quiet", "--initial-branch=main"]);
  const ident = (prefix, value) => {
    const [, name, email] = value.match(/^(.*) <(.*)>$/);
    return { [`GIT_${prefix}_NAME`]: name, [`GIT_${prefix}_EMAIL`]: email };
  };
  const shas = commits.map(({ message, author = maintainer, committer = maintainer }, index) => {
    writeFileSync(join(dir, "file.txt"), String(index));
    git(["add", "file.txt"]);
    git(["-c", "commit.gpgsign=false", "commit", "--quiet", "-m", message], { ...ident("AUTHOR", author), ...ident("COMMITTER", committer) });
    return git(["rev-parse", "HEAD"]);
  });
  return { dir, shas };
}

const run = (dir, args) => spawnSync(process.execPath, [script, ...args], { cwd: dir, encoding: "utf8", env: { ...process.env, GITHUB_ACTIONS: "true" } });

test("attribution reads every commit in base..head from git, with its raw identities and whole message", () => {
  const { dir, shas } = repository([
    { message: "Start" },
    { message: "Button: a fix\n\nCo-authored-by: Claude <noreply@anthropic.com>", committer: `GitHub <${GITHUB}>` },
    { message: "Dialog: a fix", author: "Bot <bot@example.com>" },
  ]);
  const git = (args) => execFileSync("git", args, { cwd: dir, encoding: "utf8" });
  const commits = readCommits(shas[0], shas[2], git);
  assert.deepEqual(
    commits.map(({ sha, authorEmail, committerEmail, message }) => ({ sha, authorEmail, committerEmail, message })),
    [
      { sha: shas[2], authorEmail: "bot@example.com", committerEmail: MAINTAINER.email, message: "Dialog: a fix" },
      { sha: shas[1], authorEmail: MAINTAINER.email, committerEmail: GITHUB, message: "Button: a fix\n\nCo-authored-by: Claude <noreply@anthropic.com>" },
    ],
  );
  // On the command line: each problem with its commit, field and fix, as a GitHub error; and a failing status.
  const result = run(dir, [shas[0], shas[2]]);
  assert.equal(result.status, 1, result.stdout + result.stderr);
  const lines = result.stdout.trim().split("\n");
  assert.equal(lines.length, 2, result.stdout);
  assert.match(lines[0], new RegExp(`^::error::attribution: commit ${shas[2].slice(0, 12)}, author: Bot <bot@example\\.com> may not author here .*\\. Fix: re-author`));
  assert.match(lines[1], new RegExp(`^::error::attribution: commit ${shas[1].slice(0, 12)}, message line 3: "Co-authored-by: Claude <noreply@anthropic\\.com>" credits an AI tool or a bot\\. Fix: remove the line`));
  // A clean range passes and says how many commits it read.
  const one = repository([{ message: "Start" }, { message: "Button: a fix" }]);
  const passed = run(one.dir, one.shas);
  assert.equal(passed.status, 0, passed.stdout + passed.stderr);
  assert.match(passed.stdout, /^attribution: \S+ holds 1 commit, with no AI attribution/m);
});

test("attribution never passes a range it cannot read: a missing or unknown end, an empty range, or no repository", () => {
  const { dir, shas } = repository([{ message: "Start" }, { message: "Next" }]);
  const cases = [
    [[], /no base commit was given/],
    [[shas[0]], /no head commit was given/],
    [["", shas[1]], /no base commit was given/],
    [["f".repeat(40), shas[1]], new RegExp(`the base commit ${"f".repeat(40)} is not in this checkout`)],
    [[shas[0], "origin/main"], /the head commit origin\/main is not in this checkout/],
    [[shas[1], shas[0]], /holds no commits/],
    [[shas[1], shas[1]], /holds no commits/],
  ];
  for (const [args, message] of cases) {
    const result = run(dir, args);
    assert.equal(result.status, 1, `${args.join("..")}: ${result.stdout}`);
    assert.match(result.stdout, /^::error::attribution: /m);
    assert.match(result.stdout, message);
  }
  // Outside a repository, and when git itself fails mid-read.
  assert.equal(run(scratchDir("ouro-attribution-none-"), shas).status, 1);
  const lines = [];
  const failing = (args) => {
    if (args[0] === "rev-parse") return "";
    throw new Error("fatal: bad object");
  };
  assert.throws(() => readCommits("a", "b", failing), /bad object/);
  assert.equal(main(["a", "b"], { git: failing, log: (line) => lines.push(line), actions: false }), 1);
  assert.match(lines.join("\n"), /^attribution: fatal: bad object/);
});
